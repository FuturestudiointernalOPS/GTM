"""Small end-to-end demo: one search per side, the found pages, a draft message.

Why this command: a weekly run is the production path, but it is too heavy for a
demonstration (25 queries, page reads, database). This module runs the same
building blocks on a deliberately small scale:

- one creator query and one buyer query, taken from the weekly rotation;
- the list of creator pages and company pages they returned;
- a short Telegram notification an operator can send to the configured chat;
- an outreach draft for one recipient, generated by the model and never sent
  automatically. ``--send-draft`` sends that draft to the configured chat so a
  human can review it; the bot does not read replies and never contacts the
  target.

Both searches use Exa on purpose: SerpApi answers Google with redirect links
(``google.com/goto?url=...``), which are not URLs a demo should display as
companies. The buyer query keeps its pool id but runs through Exa in its
natural-language form; the output still shows which service the real rotation
would use. The real pipeline still routes each query to its configured service.

Examples::

    python -m workflows.demo --week 45
    python -m workflows.demo --week 45 --recipient buyer --num-results 5
    python -m workflows.demo --send-telegram
    python -m workflows.demo --send-draft
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
import textwrap
from collections.abc import Callable
from dataclasses import replace
from datetime import UTC, datetime
from urllib.parse import urlsplit

from ai import get_ai_provider
from integrations import telegram, webreader
from workflows import buyer_hunt, creator_hunt, query_pool, telegram_report

log = logging.getLogger("gtm.demo")

DEFAULT_RESULTS = 5

# The most readable company queries for a demonstration. The rotation still
# decides which ones are available this week; these are preferred when present.
PREFERRED_BUYER_IDS = (
    "buyer.category.game_studios",
    "buyer.category.mobile_publishers",
    "buyer.category.gaming_pc_shops",
)

# The model only needs enough context to quote one element; the whole page is
# not useful and would make the demonstration slower.
MAX_PAGE_CHARS = 1500

# A demonstration does not need to try every page: three readable candidates are
# enough, and each failed attempt can cost a page read.
MAX_DRAFT_ATTEMPTS = 3


def build_demo(
    *,
    week: int | None = None,
    num_results: int = DEFAULT_RESULTS,
    recipient: str = "creator",
    no_ai: bool = False,
    provider=None,
    read: Callable[..., webreader.PageRead] = webreader.read_url,
) -> dict:
    """Run the demonstration and return everything it produced.

    ``provider`` and ``read`` are injected so a test can run without network or
    model. Without a provider (``no_ai``), the search and the lists still run;
    only the outreach draft is skipped.
    """
    week = week if week is not None else query_pool.current_week()
    creator_query = _first_exa(query_pool.creator_plan(week))
    planned_buyer = _first_buyer_query(query_pool.buyer_plan(week))
    # The rotation sends buyer queries to SerpApi. For the demonstration, run
    # the same pool query through Exa so the list shows real company URLs
    # instead of Google redirect links.
    buyer_query = replace(planned_buyer, service="exa")

    creator_pages = creator_hunt.hunt_plan(
        (creator_query,),
        num_results=num_results,
    )["pages"]
    buyer_pages = buyer_hunt.hunt_plan(
        (buyer_query,),
        num_results=num_results,
    )["pages"]

    creators = [
        _as_creator_page(page)
        for page in creator_pages
        if _looks_like_profile(page["url"])
    ]
    companies = [_as_company_page(page) for page in buyer_pages]

    runs = [
        _search_line(creator_query, len(creator_pages), side="creator"),
        _search_line(
            buyer_query,
            len(companies),
            side="buyer",
            planned_service=planned_buyer.service,
        ),
    ]
    outreach = {"recipient": None, "draft": None, "error": None}
    targets = _target_order(creators, companies, recipient)
    if not targets:
        outreach["error"] = "aucune page trouvée pour ce destinataire"
    elif no_ai:
        outreach["error"] = "génération désactivée (--no-ai)"
    else:
        if provider is None:
            provider = get_ai_provider()
        outreach = _draft_for_first_readable(targets, provider, read)

    notification = _notification(runs, creators, companies, outreach)
    return {
        "week": week,
        "queries": runs,
        "creators": creators,
        "companies": companies,
        "telegram_notification": notification,
        "outreach": outreach,
    }


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    logging.basicConfig(
        level=args.log_level.upper(),
        format="%(asctime)s %(levelname)s %(name)s %(message)s",
    )

    try:
        report = build_demo(
            week=args.week,
            num_results=args.num_results,
            recipient=args.recipient,
            no_ai=args.no_ai,
        )
    except (RuntimeError, ValueError) as error:
        log.error("%s", error)
        return 2

    sent = False
    send_error = None
    if args.send_telegram:
        # A long summary is cut between sections: Telegram refuses > 4096 chars.
        parts = telegram_report.split(report["telegram_notification"])
        sent = all([telegram.send_message_safely(part) for part in parts])
        if not sent:
            send_error = "Telegram n'a pas accepté le message (voir le log)"

    report["telegram_sent"] = sent
    report["telegram_error"] = send_error

    draft_sent = False
    draft_error = None
    if args.send_draft:
        text = _validation_message(report["outreach"])
        if text is None:
            draft_error = "aucun brouillon à envoyer"
        else:
            draft_sent = telegram.send_message_safely(text)
            if not draft_sent:
                draft_error = "Telegram n'a pas accepté le brouillon (voir le log)"

    report["draft_sent"] = draft_sent
    report["draft_error"] = draft_error
    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=2))
    else:
        print(render_text(report))
    return 1 if (send_error or draft_error) else 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m workflows.demo",
        description="Demonstration: search, found pages, Telegram message.",
    )
    parser.add_argument(
        "--week",
        type=int,
        default=None,
        help="rotation week (default: current ISO week)",
    )
    parser.add_argument(
        "--num-results",
        type=int,
        default=DEFAULT_RESULTS,
        help="results per search (default: 5)",
    )
    parser.add_argument(
        "--recipient",
        choices=("creator", "buyer"),
        default="creator",
        help="who receives the draft (default: creator)",
    )
    parser.add_argument(
        "--no-ai",
        action="store_true",
        help="skip the outreach draft and run only the search",
    )
    parser.add_argument(
        "--send-telegram",
        action="store_true",
        help="send the summary notification to the configured chat",
    )
    parser.add_argument(
        "--send-draft",
        action="store_true",
        help="send the outreach draft to the configured chat for human review",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="print JSON instead of the readable report",
    )
    parser.add_argument("--log-level", default="INFO")
    return parser


def _first_exa(plan) -> query_pool.Query:
    """Take the first Exa query of a plan, or stop with a clear message."""
    for query in plan:
        if query.service == "exa":
            return query
    raise ValueError("the plan contains no Exa query to demonstrate")


def _first_query(plan) -> query_pool.Query:
    """Take the first query of a plan, or stop with a clear message."""
    for query in plan:
        return query
    raise ValueError("the plan contains no query to demonstrate")


def _first_buyer_query(plan) -> query_pool.Query:
    """Prefer a company-category query: ad-label searches mostly return articles."""
    by_id = {query.id: query for query in plan}
    for query_id in PREFERRED_BUYER_IDS:
        if query_id in by_id:
            return by_id[query_id]
    for query in plan:
        if query.block == "buyers.categories":
            return query
    return _first_query(plan)


def _as_creator_page(page: dict) -> dict:
    return {
        "title": page.get("title") or page["url"],
        "url": page["url"],
        "platform": page.get("platform"),
        "query_used": page.get("query_used"),
    }


def _as_company_page(page: dict) -> dict:
    return {
        "title": page.get("title") or page["url"],
        "url": page["url"],
        "query_used": page.get("query_used"),
    }


def _search_line(
    query: query_pool.Query,
    found: int,
    *,
    side: str,
    planned_service: str | None = None,
) -> dict:
    line = {
        "side": side,
        "id": query.id,
        "text": query.text,
        "service": query.service,
        "target": query.target,
        "pages_found": found,
    }
    if planned_service and planned_service != query.service:
        line["planned_service"] = planned_service
        line["note"] = "forme naturelle Exa pour la démo"
    return line


def _target_order(creators: list[dict], companies: list[dict], recipient: str):
    """Return the draft candidates in the requested order."""
    return creators + companies if recipient == "creator" else companies + creators


def _looks_like_profile(url: str) -> bool:
    """True for a page that can be a creator profile, not a listing or a video."""
    parts = urlsplit(url)
    path = parts.path.strip("/")
    if not path:
        return False
    first = path.split("/", 1)[0].lower()
    return not (
        first.startswith(("clip", "playlist", "shorts", "video", "watch"))
        or first
        in {
            "category",
            "directory",
            "login",
            "results",
            "search",
            "settings",
            "signup",
            "tags",
        }
    )


def _draft_for_first_readable(targets: list[dict], provider, read) -> dict:
    """Try a few candidates and keep the first draft that is not empty.

    A profile page can be rendered by JavaScript and return no text; the model
    is then right to refuse a message. Moving to the next candidate keeps the
    demonstration useful without inventing a personal element.
    """
    last = {"recipient": None, "draft": None, "error": "aucun brouillon généré"}
    for target in targets[:MAX_DRAFT_ATTEMPTS]:
        last = _draft_outreach(target, provider, read)
        message = (last.get("draft") or {}).get("message") or ""
        if message.strip():
            return last
    return last


def _draft_outreach(target: dict, provider, read) -> dict:
    """Read the page, ask the model for a draft, and never send anything."""
    page = read(target["url"], max_chars=MAX_PAGE_CHARS)
    if page.error:
        return {
            "recipient": target,
            "draft": None,
            "error": f"page non lisible ({page.error}) : {target['url']}",
        }
    excerpt = (page.text or "").strip()
    if not excerpt:
        return {
            "recipient": target,
            "draft": None,
            "error": (
                f"page sans texte lisible : aucun élément à citer ({target['url']})"
            ),
        }
    payload = {
        "recipient_kind": "creator" if target.get("platform") else "buyer",
        "name": target["title"],
        "url": target["url"],
        "platform": target.get("platform"),
        "discovered_with": target.get("query_used"),
        "public_page_title": page.title,
        "public_page_excerpt": excerpt,
    }
    try:
        draft = provider.generate_outreach(payload)
    except Exception as error:  # noqa: BLE001 - a failed draft must not hide the demo
        return {
            "recipient": target,
            "draft": None,
            "error": f"génération impossible : {error}",
        }
    error = None
    if not (draft.get("message") or "").strip():
        error = "le modèle n'a trouvé aucun élément vérifié : brouillon vide"
    return {"recipient": target, "draft": draft, "error": error}


def _validation_message(outreach: dict) -> str | None:
    """Build the message sent to the operator for review, or None without a draft."""
    target = outreach.get("recipient")
    draft = outreach.get("draft")
    if not target or not draft:
        return None
    message = (draft.get("message") or "").strip()
    if not message:
        return None
    label = target.get("platform") or "Entreprise"
    return "\n".join(
        [
            "BROUILLON À VALIDER — aucun envoi automatique",
            "",
            f"Cible : {target['title']} ({label})",
            f"Page : {target['url']}",
            f"Canal : {draft.get('channel') or '—'}",
            f"Élément cité : {draft.get('personalisation') or '—'}",
            "",
            "Message proposé :",
            message,
        ]
    )


def _notification(
    runs: list[dict],
    creators: list[dict],
    companies: list[dict],
    outreach: dict,
) -> str:
    """Build the Telegram summary, in the Monday report layout.

    The demo has no score, spend or sanctions step: those parts say "not
    measured yet" instead of showing invented numbers.
    """
    # Count what is listed below (profiles only), not every page the search hit.
    shown = {
        "creator": ("Creators found", len(creators)),
        "buyer": ("Companies found", len(companies)),
    }
    funnel = tuple(
        telegram_report.Target(
            *shown.get(run["side"], (run["side"], run["pages_found"])),
            note=f"search: {run['text']}",
        )
        for run in runs
    )

    drafts: tuple[telegram_report.Draft, ...] = ()
    blockers: tuple[str, ...] = ()
    target = outreach.get("recipient")
    message = ((outreach.get("draft") or {}).get("message") or "").strip()
    if target and message:
        drafts = (
            telegram_report.Draft(
                _ref(target, creators, companies),
                telegram_report.display_name(target.get("title"), target["url"]),
                (outreach["draft"].get("channel") or "message") + " (RU)",
            ),
        )
    if outreach.get("error"):
        blockers = (f"Draft: {outreach['error']}",)

    now = datetime.now(UTC)
    report = telegram_report.WeeklyReport(
        run_date=now.date(),
        finished_at=f"{now:%H:%M} UTC",
        funnel=funnel,
        creators=telegram_report.candidates_from_pages(creators),
        buyers=telegram_report.candidates_from_pages(companies),
        blockers=blockers,
        drafts=drafts,
        demo=True,
        draft_note=("The draft text is shown in the console; it is not sent.",),
    )
    return telegram_report.render(report)


def _ref(target: dict, creators: list[dict], companies: list[dict]) -> str:
    """C1, B2...: the draft's place in the lists shown above it."""
    for prefix, pages in (("C", creators), ("B", companies)):
        for index, page in enumerate(pages, start=1):
            if page["url"] == target["url"]:
                return f"{prefix}{index}"
    return "—"


def render_text(report: dict) -> str:
    """Turn the report into a readable page for a live demonstration."""
    lines = [
        "=" * 64,
        f" DÉMO GTM — SEMAINE {report['week']}",
        "=" * 64,
    ]

    _section(lines, "1. RECHERCHE")
    for run in report["queries"]:
        label = "Créateurs" if run.get("side") == "creator" else "Entreprises"
        lines.append(f"{label:<12} {run['id']}  ({run['pages_found']} page(s))")
        lines.append(f"{'':<12} « {run['text']} »")
        if run.get("planned_service"):
            lines.append(
                f"{'':<12} forme naturelle Exa ; le plan réel utilise "
                f"{run['planned_service']}"
            )

    _section(lines, f"2. CRÉATEURS TROUVÉS ({len(report['creators'])})")
    lines.extend(_page_lines(report["creators"], with_platform=True))

    _section(lines, f"3. ENTREPRISES TROUVÉES ({len(report['companies'])})")
    lines.extend(_page_lines(report["companies"], with_platform=False))

    _section(lines, "4. RÉSUMÉ TELEGRAM")
    lines.extend(report["telegram_notification"].splitlines())

    _section(lines, "5. BROUILLON D'APPROCHE — À VALIDER, NON ENVOYÉ")
    lines.extend(_outreach_lines(report["outreach"]))

    _section(lines, "6. ENVOI TELEGRAM")
    if report.get("telegram_sent"):
        lines.append("Envoyé au chat configuré.")
    elif report.get("telegram_error"):
        lines.append(f"Échec : {report['telegram_error']}")
    else:
        lines.append("Non demandé (ajoutez --send-telegram).")

    _section(lines, "7. ENVOI DU BROUILLON POUR VALIDATION")
    if report.get("draft_sent"):
        lines.append("Brouillon envoyé au chat configuré pour validation.")
    elif report.get("draft_error"):
        lines.append(f"Échec : {report['draft_error']}")
    else:
        lines.append("Non demandé (ajoutez --send-draft).")

    return "\n".join(lines)


def _section(lines: list[str], title: str) -> None:
    lines.append("")
    lines.append(title)
    lines.append("-" * 64)


def _page_lines(pages: list[dict], *, with_platform: bool) -> list[str]:
    if not pages:
        return ["Aucune page."]
    lines = []
    for index, page in enumerate(pages, 1):
        platform = (
            f"[{page['platform']}] " if with_platform and page.get("platform") else ""
        )
        lines.append(f"{index}. {platform}{page['title']}")
        lines.append(f"   {page['url']}")
        lines.append(f"   requête : {page.get('query_used') or '—'}")
    return lines


def _outreach_lines(outreach: dict) -> list[str]:
    target = outreach.get("recipient")
    if target:
        label = target.get("platform") or "Entreprise"
        lines = [
            f"Destinataire : {target['title']} ({label})",
            f"Page         : {target['url']}",
        ]
    else:
        lines = ["Aucun destinataire."]

    draft = outreach.get("draft")
    if draft:
        lines.append(f"Canal        : {draft.get('channel') or '—'}")
        if draft.get("subject"):
            lines.append(f"Objet        : {draft['subject']}")
        lines.append(f"Élément cité : {draft.get('personalisation') or '—'}")
        lines.append("")
        message = (draft.get("message") or "(brouillon vide)").strip()
        lines.extend(
            textwrap.fill(
                message,
                width=76,
                break_long_words=False,
                break_on_hyphens=False,
            ).splitlines()
        )
    if outreach.get("error"):
        lines.append(f"Attention : {outreach['error']}")
    return lines


if __name__ == "__main__":
    sys.exit(main())
