#!/usr/bin/env bash
# Local PostgreSQL container for the GTM tool.
#
# Why plain docker and not Compose: the server does not ship the compose plugin,
# so this script uses only commands that work both there and on a laptop.
#
# Settings precedence: environment > db/postgres/container.env > repository
# .env > defaults. Only POSTGRES_* keys are read, so no API key ever reaches the
# database container.
#
# Usage: db/postgres/container.sh <command>
#   up        create or start the container, wait, apply the schema if empty
#   down      stop and remove the container (the volume is kept)
#   reset     remove the container AND the volume (asks for confirmation)
#   migrate   apply 003, 004, 005 and 006 to an existing database
#   check     replay smoke_test.sql (ends with ROLLBACK, leaves nothing)
#   test      run tests/test_postgres_live.py against this container
#   psql      open an interactive psql session
#   status    show the container and the volume
#   logs      follow the container logs
#
# The first `up` without POSTGRES_PASSWORD generates one into
# db/postgres/container.env (mode 600, ignored by Git) instead of printing a
# secret. Add the matching DATABASE_URL to the repository .env for the app.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SCHEMA_DIR="$ROOT/db/postgres"
SETTINGS_FILE="${GTM_POSTGRES_ENV:-$SCHEMA_DIR/container.env}"

# Tested digest for postgres:17-alpine. Update it deliberately, then re-run the
# tests: a database image change is a change like any other.
DEFAULT_IMAGE="postgres:17-alpine@sha256:526f86d93c6ea08fd3f1fe5605650cacc781b2c6013169a0ad8f42c7d3d84f32"

# Look a setting up with the documented precedence, without sourcing .env.
lookup() {
    local key="$1" value file
    if [ -n "${!key+x}" ]; then
        printf '%s' "${!key}"
        return
    fi
    for file in "$SETTINGS_FILE" "$ROOT/.env"; do
        [ -f "$file" ] || continue
        value="$(grep -E "^[[:space:]]*${key}=" "$file" | tail -n 1 | cut -d= -f2- || true)"
        if [ -n "$value" ]; then
            value="${value%$'\r'}"
            value="${value#\"}"
            value="${value%\"}"
            value="${value#\'}"
            value="${value%\'}"
            printf '%s' "$value"
            return
        fi
    done
}

NAME="$(lookup POSTGRES_CONTAINER)"
NAME="${NAME:-gtm-postgres}"
VOLUME="$(lookup POSTGRES_VOLUME)"
VOLUME="${VOLUME:-gtm-postgres-data}"
IMAGE="$(lookup POSTGRES_IMAGE)"
IMAGE="${IMAGE:-$DEFAULT_IMAGE}"
DB="$(lookup POSTGRES_DB)"
DB="${DB:-gtm}"
DB_USER="$(lookup POSTGRES_USER)"
DB_USER="${DB_USER:-gtm}"
DB_PASSWORD="$(lookup POSTGRES_PASSWORD)"
PORT="$(lookup POSTGRES_PORT)"
PORT="${PORT:-5432}"

PYTHON="${PYTHON:-}"
if [ -z "$PYTHON" ] && [ -x "$ROOT/.venv/bin/python" ]; then
    PYTHON="$ROOT/.venv/bin/python"
fi
PYTHON="${PYTHON:-python3}"

require_docker() {
    command -v docker >/dev/null 2>&1 || {
        echo "docker is not installed or not in PATH" >&2
        exit 1
    }
}

container_exists() {
    docker container inspect "$NAME" >/dev/null 2>&1
}

is_running() {
    [ "$(docker inspect -f '{{.State.Running}}' "$NAME" 2>/dev/null || echo false)" = "true" ]
}

require_running() {
    if ! container_exists; then
        echo "Container $NAME does not exist. Run: $0 up" >&2
        exit 1
    fi
    if ! is_running; then
        echo "Container $NAME is stopped. Run: $0 up" >&2
        exit 1
    fi
}

ensure_password() {
    [ -n "$DB_PASSWORD" ] && return 0
    local generated
    generated="$(openssl rand -hex 24 2>/dev/null || tr -dc 'a-f0-9' </dev/urandom | head -c 48)"
    umask 077
    {
        echo "# Generated by db/postgres/container.sh on first start."
        echo "# Ignored by Git. The application DATABASE_URL must use this password."
        echo "POSTGRES_DB=$DB"
        echo "POSTGRES_USER=$DB_USER"
        echo "POSTGRES_PASSWORD=$generated"
        echo "POSTGRES_PORT=$PORT"
    } >"$SETTINGS_FILE"
    chmod 600 "$SETTINGS_FILE"
    DB_PASSWORD="$generated"
    echo "Generated a local password in ${SETTINGS_FILE#"$ROOT"/} (mode 600, ignored by Git)." >&2
}

wait_ready() {
    local status attempt
    printf 'Waiting for PostgreSQL'
    for attempt in $(seq 1 60); do
        status="$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$NAME" 2>/dev/null || echo missing)"
        case "$status" in
            healthy)
                printf ' ready.\n'
                return 0
                ;;
            unhealthy | exited | dead)
                printf ' failed (%s).\n' "$status" >&2
                docker logs --tail 40 "$NAME" >&2 || true
                return 1
                ;;
        esac
        printf '.'
        sleep 2
    done
    printf ' timed out.\n' >&2
    docker logs --tail 40 "$NAME" >&2 || true
    return 1
}

psql_file() {
    docker exec "$NAME" psql -U "$DB_USER" -d "$DB" -v ON_ERROR_STOP=1 -f "/schema/$1"
}

init_schema() {
    local present
    present="$(docker exec "$NAME" psql -U "$DB_USER" -d "$DB" -tAc "SELECT to_regclass('public.record')")"
    if [ -n "$present" ]; then
        echo "Schema already present ($present); nothing applied."
        return 0
    fi
    echo "Applying 001_schema.sql and 002_seed_reference.sql..."
    psql_file 001_schema.sql
    psql_file 002_seed_reference.sql
    echo "Schema applied."
}

cmd_up() {
    require_docker
    ensure_password
    docker volume create "$VOLUME" >/dev/null
    if container_exists; then
        if is_running; then
            echo "Container $NAME already running."
        else
            docker start "$NAME" >/dev/null
            echo "Started container $NAME."
        fi
        current_image="$(docker inspect -f '{{.Config.Image}}' "$NAME" 2>/dev/null || true)"
        if [ "$current_image" != "$IMAGE" ]; then
            echo "Warning: $NAME runs $current_image, not $IMAGE. Run 'reset --yes' then 'up' to switch." >&2
        fi
    else
        docker run --detach \
            --name "$NAME" \
            --restart unless-stopped \
            --env POSTGRES_DB="$DB" \
            --env POSTGRES_USER="$DB_USER" \
            --env POSTGRES_PASSWORD="$DB_PASSWORD" \
            --publish "127.0.0.1:${PORT}:5432" \
            --volume "${VOLUME}:/var/lib/postgresql/data" \
            --volume "${SCHEMA_DIR}:/schema:ro" \
            --health-cmd "pg_isready -U ${DB_USER} -d ${DB}" \
            --health-interval 5s \
            --health-timeout 5s \
            --health-retries 30 \
            --log-opt max-size=10m \
            --log-opt max-file=3 \
            "$IMAGE" >/dev/null
        echo "Created container $NAME from $IMAGE."
    fi
    wait_ready
    init_schema
    echo
    echo "PostgreSQL is listening on 127.0.0.1:${PORT} (database ${DB}, user ${DB_USER})."
    echo "Credentials: ${SETTINGS_FILE#"$ROOT"/} (mode 600, never commit it)."
    echo "Application URL: postgresql://${DB_USER}:<password>@127.0.0.1:${PORT}/${DB}"
}

cmd_down() {
    if ! container_exists; then
        echo "Container $NAME does not exist."
        return 0
    fi
    docker stop "$NAME" >/dev/null 2>&1 || true
    docker rm "$NAME" >/dev/null 2>&1 || true
    echo "Container $NAME removed; volume $VOLUME kept."
}

cmd_reset() {
    if [ "${1:-}" != "--yes" ]; then
        if [ ! -t 0 ]; then
            echo "Refusing to delete data without --yes (no terminal to confirm)." >&2
            exit 1
        fi
        printf 'This deletes container %s AND volume %s (all data). Type "yes": ' "$NAME" "$VOLUME"
        read -r answer
        [ "$answer" = "yes" ] || {
            echo "Aborted."
            exit 1
        }
    fi
    cmd_down >/dev/null 2>&1 || true
    docker volume rm "$VOLUME" >/dev/null 2>&1 || true
    echo "Container $NAME and volume $VOLUME removed. The next 'up' starts empty."
}

cmd_migrate() {
    require_docker
    require_running
    psql_file 003_engagement.sql
    psql_file 004_sync.sql
    psql_file 005_evidence.sql
    psql_file 006_contact_sync.sql
    echo "Migrations 003, 004, 005 and 006 applied (idempotent)."
}

cmd_check() {
    require_docker
    require_running
    psql_file smoke_test.sql
    echo "Smoke test replayed and rolled back; nothing was kept."
}

cmd_test() {
    require_docker
    require_running
    local url="postgresql://${DB_USER}:${DB_PASSWORD}@127.0.0.1:${PORT}/${DB}"
    GTM_TEST_DATABASE_URL="$url" "$PYTHON" -m pytest -q "$ROOT/tests/test_postgres_live.py"
}

cmd_psql() {
    require_docker
    require_running
    docker exec -it "$NAME" psql -U "$DB_USER" -d "$DB" "$@"
}

cmd_status() {
    require_docker
    docker ps -a --filter "name=^/${NAME}$" \
        --format 'table {{.Names}}\t{{.Status}}\t{{.Ports}}' || true
    if docker volume inspect "$VOLUME" >/dev/null 2>&1; then
        echo "Volume: $VOLUME"
    else
        echo "Volume: $VOLUME (absent)"
    fi
}

cmd_logs() {
    require_docker
    require_running
    docker logs --tail 100 -f "$NAME"
}

usage() {
    cat <<'EOF'
Usage: db/postgres/container.sh <command>

  up        create or start the container, wait, apply the schema if empty
  down      stop and remove the container (the volume is kept)
  reset     remove the container AND the volume (asks for confirmation)
  migrate   apply 003, 004, 005 and 006 to an existing database
  check     replay smoke_test.sql (ends with ROLLBACK, leaves nothing)
  test      run tests/test_postgres_live.py against this container
  psql      open an interactive psql session
  status    show the container and the volume
  logs      follow the container logs

Settings come from the environment, then db/postgres/container.env, then the
repository .env, then defaults. The first 'up' without POSTGRES_PASSWORD
generates one into db/postgres/container.env (mode 600, ignored by Git).
EOF
}

command="${1:-help}"
if [ $# -gt 0 ]; then
    shift
fi
case "$command" in
    up) cmd_up ;;
    down) cmd_down ;;
    reset) cmd_reset "$@" ;;
    migrate) cmd_migrate ;;
    check) cmd_check ;;
    test) cmd_test ;;
    psql) cmd_psql "$@" ;;
    status) cmd_status ;;
    logs) cmd_logs ;;
    help | -h | --help) usage ;;
    *)
        echo "Unknown command: $command" >&2
        usage >&2
        exit 2
        ;;
esac
